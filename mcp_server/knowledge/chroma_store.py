"""Chroma backend for the VectorStore Protocol.

Uses the synchronous chromadb client wrapped in asyncio.to_thread to avoid
blocking the event loop (fix #4). All blocking Chroma calls are offloaded
to a thread.

Server mode vs embedded mode (fix #1):
  * If chroma_path is set  -> embedded PersistentClient (local dev/tests).
  * If chroma_host is set  -> HTTP client to a separate Chroma server
    (production on Render with persistent disk or separate service).
"""
from __future__ import annotations

import asyncio
from typing import Any

from .vectors import (
    _flatten_metadata,
    _sanitize_collection_name,
    _unflatten_metadata,
)


class ChromaVectorStore:
    """Vector store backed by Chroma (embedded PersistentClient or HTTP).

    Embeddings are generated by the injected Embedder port; Chroma stores
    them with embedding_function=None so it never downloads its own
    default ONNX model (fix #10).
    """

    MAX_BATCH = 100

    def __init__(
        self,
        embedder: Any,
        namespace: str,
        *,
        chroma_path: str | None = None,
        chroma_host: str | None = None,
        chroma_port: int = 8000,
    ) -> None:
        self._embedder = embedder
        self._dim = embedder.dim
        self._collection_name = _sanitize_collection_name(namespace)
        self._chroma_path = chroma_path
        self._chroma_host = chroma_host
        self._chroma_port = chroma_port
        self._client: Any = None
        self._collection: Any = None
        self._initialised = False
        self._embedder_fitted = False

    # --- lazy initialisation ---

    def _build_client(self) -> Any:
        """Construct the Chroma client (sync -- called inside to_thread)."""
        from chromadb.config import Settings

        settings = Settings(anonymized_telemetry=False)
        if self._chroma_host:
            import chromadb
            return chromadb.HttpClient(
                host=self._chroma_host,
                port=self._chroma_port,
                settings=settings,
            )
        if self._chroma_path:
            import chromadb
            return chromadb.PersistentClient(path=self._chroma_path, settings=settings)
        # Default: in-memory (tests only).
        import chromadb
        return chromadb.EphemeralClient(settings=settings)

    def _get_collection(self) -> Any:
        """Get or create the collection with cosine HNSW space (fix #5)."""
        return self._client.get_or_create_collection(
            name=self._collection_name,
            metadata={"hnsw:space": "cosine"},
            embedding_function=None,
        )

    async def _ensure_init(self) -> None:
        """Lazy-init the client and collection on first use."""
        if self._initialised:
            return
        self._client = await asyncio.to_thread(self._build_client)
        self._collection = await asyncio.to_thread(self._get_collection)
        self._initialised = True

    # --- lifecycle ---

    @property
    def dim(self) -> int:
        return self._dim

    async def health_check(self) -> bool:
        return await self.ready()

    async def ready(self) -> bool:
        """True if the collection exists and contains at least 1 document (fix #2)."""
        try:
            await self._ensure_init()
            return await asyncio.to_thread(self._collection.count) > 0
        except Exception:
            return False

    async def close(self) -> None:
        """Chroma clients manage connections internally; nothing to close."""
        pass

    # --- writes ---

    async def upsert_many(self, docs: list[dict[str, Any]]) -> int:
        """Bulk-index documents. Each doc: {id, text, metadata?}. Returns count."""
        if not docs:
            return 0
        await self._ensure_init()
        texts = [d["text"] for d in docs]
        embeddings = await self._embedder.embed_batch(texts, input_type="passage")
        stored = 0
        for i in range(0, len(docs), self.MAX_BATCH):
            batch = docs[i : i + self.MAX_BATCH]
            batch_emb = embeddings[i : i + self.MAX_BATCH]
            ids = [d["id"] for d in batch]
            documents = [d["text"] for d in batch]
            metadatas = [_flatten_metadata(d.get("metadata")) for d in batch]

            def _do_upsert():
                self._collection.upsert(
                    ids=ids,
                    embeddings=batch_emb,
                    documents=documents,
                    metadatas=metadatas,
                )

            await asyncio.to_thread(_do_upsert)
            stored += len(batch)
        self._embedder_fitted = True
        return stored

    async def upsert(self, doc_id: str, text: str, metadata: dict[str, Any] | None = None) -> None:
        """Single-document upsert."""
        await self._ensure_init()
        embedding = await self._embedder.embed(text, input_type="passage")
        await asyncio.to_thread(
            self._collection.upsert,
            ids=[doc_id],
            embeddings=[embedding],
            documents=[text],
            metadatas=[_flatten_metadata(metadata)],
        )

    async def delete(self, doc_id: str) -> None:
        """Delete a document by id."""
        await self._ensure_init()
        await asyncio.to_thread(self._collection.delete, ids=[doc_id])

    async def delete_many(self, doc_ids: list[str]) -> int:
        """Delete documents by ids. Returns count deleted."""
        if not doc_ids:
            return 0
        await self._ensure_init()
        for i in range(0, len(doc_ids), self.MAX_BATCH):
            batch = doc_ids[i : i + self.MAX_BATCH]
            await asyncio.to_thread(self._collection.delete, ids=batch)
        return len(doc_ids)

    # --- reads ---

    async def get(self, doc_id: str) -> dict[str, Any] | None:
        """Retrieve a document by id. Returns {id, text, metadata} or None."""
        await self._ensure_init()
        result = await asyncio.to_thread(
            self._collection.get,
            ids=[doc_id],
            include=["documents", "metadatas"],
        )
        ids = result.get("ids", [])
        if not ids or ids[0] is None:
            return None
        return {
            "id": doc_id,
            "text": (result.get("documents") or [""])[0] or "",
            "metadata": _unflatten_metadata((result.get("metadatas") or [{}])[0] or {}),
        }

    async def list_ids(self) -> list[str]:
        """List all stored document ids."""
        await self._ensure_init()
        result = await asyncio.to_thread(self._collection.get, include=["metadatas"])
        return list(result.get("ids") or [])

    async def get_all_texts(self) -> list[str]:
        """Return all stored texts (used for TF-IDF fitting)."""
        await self._ensure_init()
        result = await asyncio.to_thread(self._collection.get, include=["documents"])
        return [d for d in (result.get("documents") or []) if d]

    async def fit_embedder(self) -> int:
        """Fit an unfitted TF-IDF embedder from all stored texts."""
        texts = await self.get_all_texts()
        if hasattr(self._embedder, "fit"):
            self._embedder.fit(texts)
        self._embedder_fitted = True
        return len(texts)

    async def search(self, query: str, top_k: int = 5) -> list[dict[str, Any]]:
        """Search via query text (embedder handles embedding)."""
        if not self._embedder_fitted and hasattr(self._embedder, "_fitted"):
            await self.fit_embedder()
        query_embedding = await self._embedder.embed(query, input_type="query")
        return await self.search_by_embedding(query_embedding, top_k)

    async def search_by_embedding(
        self, query_embedding: list[float], top_k: int = 5
    ) -> list[dict[str, Any]]:
        """Return top-k most similar vectors (fix #5: cosine similarity in [0, 1]).

        Chroma returns cosine *distance* (0 = identical, 2 = opposite).
        Converted to similarity = 1 - distance, clamped to [0, 1].
        """
        if not query_embedding:
            return []
        await self._ensure_init()

        result = await asyncio.to_thread(
            self._collection.query,
            query_embeddings=[query_embedding],
            n_results=top_k,
            include=["documents", "metadatas", "distances"],
        )

        ids = result.get("ids", [[]])[0] or []
        docs = result.get("documents", [[]])[0] or []
        metadatas = result.get("metadatas", [[]])[0] or []
        distances = result.get("distances", [[]])[0] or []

        scored: list[dict[str, Any]] = []
        for i, cid in enumerate(ids):
            if cid is None:
                continue
            dist = distances[i] if i < len(distances) else 0.0
            similarity = round(max(0.0, min(1.0, 1.0 - float(dist))), 4)
            scored.append({
                "id": cid,
                "text": docs[i] if i < len(docs) else "",
                "score": similarity,
                "metadata": _unflatten_metadata(metadatas[i] if i < len(metadatas) else {}),
            })
        # Chroma returns results sorted by distance (ascending = best first).
        return scored

    async def count(self) -> int:
        await self._ensure_init()
        return await asyncio.to_thread(self._collection.count)

    async def clear(self) -> int:
        """Delete all documents. Returns count deleted."""
        ids = await self.list_ids()
        if not ids:
            return 0
        await self.delete_many(ids)
        return len(ids)

